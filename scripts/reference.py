#!/usr/bin/env python3
"""Independent reference implementation of the EasyPassword v2 algorithm.

Used to generate core/tests/golden.inc. Requires: pip install argon2-cffi
Usage: python3 scripts/reference.py > core/tests/golden.inc
"""
import hashlib, hmac, struct
from argon2.low_level import hash_secret_raw, Type

LOWER = "abcdefghijklmnopqrstuvwxyz"; UPPER = LOWER.upper(); DIGITS = "0123456789"

def derive_seed(master_key: str, identity: str) -> bytes:
    salt = hashlib.sha256(b"EasyPassword/v2/seed\0" + identity.strip().lower().encode()).digest()
    return hash_secret_raw(master_key.encode(), salt, time_cost=3, memory_cost=65536,
                           parallelism=1, hash_len=32, type=Type.ID)

def fingerprint(seed: bytes) -> str:
    tag = hmac.new(seed, b"EasyPassword/v2/fingerprint", hashlib.sha256).digest()
    bits = int.from_bytes(tag[:4], "big")
    alphabet = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
    return "".join(alphabet[(bits >> (27 - 5 * i)) & 31] for i in range(5))

def hkdf_expand(prk: bytes, info: bytes, length: int) -> bytes:
    out, t, i = b"", b"", 1
    while len(out) < length:
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest()
        out += t; i += 1
    return out[:length]

def generate(seed, site, counter, length, lower=True, upper=True, digits=True, symbols="!#$%&*+-.:=?@^_"):
    symbols = "".join(sorted(set(symbols)))
    classes = [c for c, on in ((LOWER, lower), (UPPER, upper), (DIGITS, digits), (symbols, bool(symbols))) if on]
    info = (b"EasyPassword/v2/site\0" + site.encode() + b"\0" + struct.pack("<I", counter)
            + struct.pack("<I", length) + bytes([lower | upper << 1 | digits << 2]) + symbols.encode())
    n = int.from_bytes(hkdf_expand(seed, info, 2 * length + 32), "big")
    alphabet = "".join(classes); out = []
    for _ in range(length - len(classes)):
        n, r = divmod(n, len(alphabet)); out.append(alphabet[r])
    for cls in classes:
        n, r = divmod(n, len(cls)); ch = cls[r]
        n, p = divmod(n, len(out) + 1); out.insert(p, ch)
    return "".join(out)

if __name__ == "__main__":
    seed = derive_seed("correct horse battery staple", "")
    fp = fingerprint(seed)
    cases = [("github.com", 1, 20, "!#$%&*+-.:=?@^_"), ("github.com", 2, 20, "!#$%&*+-.:=?@^_"),
             ("example.com", 1, 8, "!#$%&*+-.:=?@^_"), ("bank.com", 1, 16, ""),
             ("work@github.com", 1, 32, "!@"), ("工商银行", 3, 64, "!#$%&*+-.:=?@^_"),
             ("x", 1, 128, "!#$%&*+-.:=?@^_")]
    print("// Generated by scripts/reference.py. Do not edit.")
    print("const GOLDEN: &[(&str, u32, usize, &str, &str, &str)] = &[")
    for site, counter, length, sym in cases:
        pw = generate(seed, site, counter, length, symbols=sym)
        print(f"    ({site!r:s}, {counter}, {length}, {sym!r}, {fp!r}, {pw!r}),".replace("'", '"') if '"' not in pw + sym and "\\" not in pw + sym else
              f"    ({site!r}, {counter}, {length}, {sym!r}, {fp!r}, {pw!r}),")
    print("];")
